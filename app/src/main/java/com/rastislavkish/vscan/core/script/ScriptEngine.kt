package com.rastislavkish.vscan.core.script

import java.util.IdentityHashMap

import org.mozilla.javascript.ClassShutter
import org.mozilla.javascript.Context
import org.mozilla.javascript.ContextFactory
import org.mozilla.javascript.EvaluatorException
import org.mozilla.javascript.RhinoException
import org.mozilla.javascript.Script
import org.mozilla.javascript.Scriptable
import org.mozilla.javascript.ScriptableObject

class ScriptException(message: String): Exception(message)

// Thrown as an Error rather than an exception, so that scripts can't catch it
private class ScriptTimeout: Error()

// The sandboxed JavaScript engine for user expressions and scripts
// Scripts get the standard JavaScript objects only, no access to Java classes, and a time limit per evaluation
// Thread-safe, each evaluation runs in a Rhino context of the calling thread
object ScriptEngine {

    const val TIMEOUT_MILLIS=1000L

    private const val DEADLINE_KEY="vscan-deadline"
    private const val CACHE_SIZE=256

    private val contextFactory=object : ContextFactory() {

        override fun makeContext(): Context {
            val context=super.makeContext()
            context.languageVersion=Context.VERSION_ES6
            // Android can't load generated bytecode, and only the interpreter counts instructions for the time limit
            context.isInterpretedMode=true
            context.setClassShutter(ClassShutter { false })
            context.instructionObserverThreshold=10_000
            context.maximumInterpreterStackDepth=1000
            return context
            }

        override fun observeInstructionCount(context: Context, instructionCount: Int) {
            val deadline=context.getThreadLocal(DEADLINE_KEY) as Long? ?: return

            if (System.nanoTime()>deadline)
            throw ScriptTimeout()
            }
        }

    // The standard objects, sealed so scripts can't alter them for others, and the prototype of all scopes
    internal val sharedScope: ScriptableObject=contextFactory.call { context ->
        context.initSafeStandardObjects(null, true)
        } as ScriptableObject

    private val cache=object : LinkedHashMap<String, Script>(CACHE_SIZE, 0.75f, true) {

        override fun removeEldestEntry(eldest: MutableMap.MutableEntry<String, Script>): Boolean = size>CACHE_SIZE
        }

    // Creates a scope with the given variables, converted to JavaScript values
    fun newScope(variables: Map<String, Any?> = mapOf()): ScriptScope {
        return run { context ->
            val scope=context.newObject(sharedScope)
            scope.prototype=sharedScope
            scope.parentScope=null

            val result=ScriptScope(scope, IdentityHashMap())
            for ((name, value) in variables)
            ScriptableObject.putProperty(scope, name, result.toJs(context, value))

            result
            }
        }

    // Runs the block in a Rhino context with the time limit, translating script failures to ScriptException
    internal fun <T> run(block: (Context) -> T): T {
        return contextFactory.call { context ->
            val previousDeadline=context.getThreadLocal(DEADLINE_KEY)
            // Nested runs share the deadline of the outermost one
            if (previousDeadline==null)
            context.putThreadLocal(DEADLINE_KEY, System.nanoTime()+TIMEOUT_MILLIS*1_000_000)

            try {
                block(context)
                }
            catch (e: ScriptTimeout) {
                throw ScriptException("The script took longer than ${TIMEOUT_MILLIS} ms")
                }
            catch (e: EvaluatorException) {
                throw ScriptException("Syntax error: ${e.details()}")
                }
            catch (e: RhinoException) {
                throw ScriptException(e.details())
                }
            catch (e: StackOverflowError) {
                throw ScriptException("The script recursed too deeply")
                }
            finally {
                if (previousDeadline==null)
                context.removeThreadLocal(DEADLINE_KEY)
                }
            } as T
        }

    internal fun compile(context: Context, source: String): Script {
        synchronized(cache) {
            cache[source]?.let { return it }
            }

        val script=context.compileString(source, "script", 1, null)

        synchronized(cache) {
            cache[source]=script
            }

        return script
        }
    }

// Variables visible to scripts, scopes can be nested so that loops and processes can add their own variables
class ScriptScope internal constructor(
    internal val scriptable: Scriptable,
    // The wrappers of opaque values, shared with child scopes, so that a value is always the same JavaScript object
    private val opaqueValues: IdentityHashMap<Any, OpaqueValue>,
    ) {

    // Evaluates the source, returning the value of its last statement converted to a Kotlin value
    fun evaluate(source: String): Any? = ScriptEngine.run { context ->
        ScriptValues.fromJs(evaluateRaw(context, source))
        }

    // Evaluates a condition, with JavaScript's notion of truthiness
    fun evaluateBoolean(source: String): Boolean = ScriptEngine.run { context ->
        Context.toBoolean(evaluateRaw(context, source))
        }

    // Evaluates the source, returning the value as text, as JavaScript's String() would
    fun evaluateString(source: String): String = ScriptEngine.run { context ->
        ScriptValues.toText(evaluateRaw(context, source))
        }

    fun set(name: String, value: Any?) {
        ScriptEngine.run { context ->
            ScriptableObject.putProperty(scriptable, name, toJs(context, value))
            }
        }

    // A scope seeing all variables of this one, with its own additions and overrides
    fun child(variables: Map<String, Any?> = mapOf()): ScriptScope = ScriptEngine.run { context ->
        val child=context.newObject(scriptable)
        child.prototype=scriptable
        child.parentScope=null

        val result=ScriptScope(child, opaqueValues)
        for ((name, value) in variables)
        ScriptableObject.putProperty(child, name, result.toJs(context, value))

        result
        }

    internal fun evaluateRaw(context: Context, source: String): Any? {
        return ScriptEngine.compile(context, source).exec(context, scriptable)
        }

    internal fun childWithRaw(context: Context, variables: Map<String, Any?>): ScriptScope {
        val child=context.newObject(scriptable)
        child.prototype=scriptable
        child.parentScope=null

        for ((name, value) in variables)
        ScriptableObject.putProperty(child, name, value)

        return ScriptScope(child, opaqueValues)
        }

    internal fun toJs(context: Context, value: Any?): Any? {
        synchronized(opaqueValues) {
            return ScriptValues.toJs(context, scriptable, value, opaqueValues)
            }
        }
    }
